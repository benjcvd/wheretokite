#!/usr/bin/env python3
"""Which spots Météo-France AROME 1.3 km covers (WHE-57).

The app reads Météo-France "seamless": AROME 1.3 km for about the next 40 h where AROME
exists, ARPEGE 11 km elsewhere and after that. AROME's footprint isn't a lat/lon box (it
covers Valencia but not Cartagena, Trieste but not Ancona), so each spot is asked once:
does Open-Meteo return AROME HD wind on the spot's beach cell?

Writes Sources/KiteCore/AromeCoverage.swift (spot ids inside / outside). Spots added to the
catalogue later are "unknown" until this is re-run: the app then just says "Météo-France".

    python3 tools/backtest/arome_coverage.py          # from the repo root, ~800 location calls
"""
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

API = "https://api.open-meteo.com/v1/forecast"
OUT = "Sources/KiteCore/AromeCoverage.swift"


def ask(spots):
    """True / False per spot; None when Open-Meteo refuses the whole request."""
    body = urllib.parse.urlencode({
        "latitude": ",".join(f"{s['latitude']:.4f}" for s in spots),
        "longitude": ",".join(f"{s['longitude']:.4f}" for s in spots),
        "models": "meteofrance_arome_france_hd",
        "hourly": "wind_speed_10m",
        "forecast_days": "1",
        "cell_selection": "land",
    }).encode()
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(API, data=body), timeout=60) as r:
                data = json.load(r)
            break
        except urllib.error.HTTPError as e:
            if e.code == 400:
                return None  # e.g. "No data is available for this location"
            if e.code == 429:
                time.sleep(65)
                continue
            raise
    else:
        raise RuntimeError("Open-Meteo kept refusing")
    data = data if isinstance(data, list) else [data]
    return [any(v is not None for v in d.get("hourly", {}).get("wind_speed_10m", [])) for d in data]


def check(spots):
    got = ask(spots)
    if got is not None:
        return dict(zip((s["id"] for s in spots), got))
    if len(spots) == 1:
        return {spots[0]["id"]: False}
    mid = len(spots) // 2
    return {**check(spots[:mid]), **check(spots[mid:])}


def main():
    cat = json.load(open("Data/spots.json"))
    spots = cat["spots"] if isinstance(cat, dict) else cat
    result = {}
    for i in range(0, len(spots), 50):
        result.update(check(spots[i:i + 50]))
        print(f"{min(i + 50, len(spots))}/{len(spots)}", file=sys.stderr)
    inside = sorted(k for k, v in result.items() if v)
    outside = sorted(k for k, v in result.items() if not v)

    def lines(ids):
        return "\n".join(f'        "{i}",' for i in ids)

    with open(OUT, "w") as f:
        f.write(f"""// Generated by tools/backtest/arome_coverage.py on {time.strftime('%Y-%m-%d')}. Don't edit.
// Which spots Météo-France AROME 1.3 km covers (Open-Meteo, beach cell). WHE-57.

enum AromeCoverage {{
    static let inside: Set<String> = [
{lines(inside)}
    ]
    static let outside: Set<String> = [
{lines(outside)}
    ]
}}
""")
    print(f"{len(inside)} inside, {len(outside)} outside -> {OUT}")


if __name__ == "__main__":
    main()
